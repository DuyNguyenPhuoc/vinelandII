import math

def percentile_for(standard):
    """Vineland percentile from standard score (mean 100, SD 15), clamped 1..99."""
    z = (standard - 100) / 15.0
    p = 0.5 * (1 + math.erf(z / math.sqrt(2))) * 100
    if p < 1: return 1
    if p > 99: return 99
    return int(round(p))

def domain_rows(m):
    """{std: sumV|(lo,hi)} -> sorted [{sumVMin,sumVMax,standard,percentile}]."""
    rows = []
    for std, v in m.items():
        lo, hi = v if isinstance(v, tuple) else (v, v)
        rows.append({"sumVMin": lo, "sumVMax": hi, "standard": std,
                     "percentile": percentile_for(std)})
    rows.sort(key=lambda r: r["sumVMin"])
    return rows

def build_by_age():
    out = []
    for label, doms in BANDS.items():
        mn, mx = BAND_MONTHS[label]
        entry = {"ageBandRaw": label, "minMonths": mn, "maxMonths": mx, "domainStandard": {}}
        for dom in ("communication","dailyLiving","socialization","motor"):
            if dom in doms:
                entry["domainStandard"][dom] = domain_rows(doms[dom])
        comp = resolve_composite(label)
        if comp:
            entry["composite"] = domain_rows(comp)
        out.append(entry)
    out.sort(key=lambda e: e["minMonths"])
    return out

